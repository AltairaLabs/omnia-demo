#!/usr/bin/env bash
# The Omnia Helm values this demo needs on your install, written from site.yaml
# to out/omnia-values.yaml (OUT overrides the path). Merge them into your
# install's values. It makes no Azure or cluster calls.
#
#   deploy/azure/omnia-values.sh
#
# It prints the hosts your install's TLS certificate must cover.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# shellcheck source=lib.sh
source "$here/lib.sh"
# shellcheck source=hosts.sh
source "$here/hosts.sh"

out="${OUT:-$here/../../out/omnia-values.yaml}"

# Required values are resolved here, at the top level, so a missing one stops
# the script (bash clears errexit inside $(...) helpers).
zone="$(site_req dns.zone)"
gw_name="$(site_req gateway.name)"
gw_ns="$(site_req gateway.namespace)"
gw_section="$(site_req gateway.sectionName)"
dashboard="$(site_req dashboardHost)"
root="$(site_get omnia.valuesRoot)"

# The identity providers whose tokens the operator accepts as a user's proof.
# Each is a stand-in edge in this repo (docs/stand-ins.md): it signs the token
# of the user it asserts and serves its JWKS in-cluster. A real install lists
# its own IdP (Entra, Okta) here instead.
issuers=(
  http://larkmere-portal.larkmere-mutual.svc.cluster.local:8080
  http://card-callers.larkmere-mutual.svc.cluster.local:8080
  http://wrenmoor-site.wrenmoor-energy.svc.cluster.local:8080
  http://assistant-page.ellens-assistant.svc.cluster.local:8080
)

GW_NAME="$gw_name" GW_NS="$gw_ns" GW_SECTION="$gw_section" ZONE="$zone"
export GW_NAME GW_NS GW_SECTION ZONE

doc="$(yq e -n '
  .operator.defaultExposure.enabled = true |
  .operator.defaultExposure.baseDomain = strenv(ZONE) |
  .operator.defaultExposure.gateway.name = strenv(GW_NAME) |
  .operator.defaultExposure.gateway.namespace = strenv(GW_NS) |
  .operator.defaultExposure.gateway.sectionName = strenv(GW_SECTION)')"
for iss in "${issuers[@]}"; do
  export ISS="$iss"
  doc="$(printf '%s\n' "$doc" | yq e '.operator.delegationAPI.trustedIssuers += [strenv(ISS) + "=" + strenv(ISS) + "/.well-known/jwks.json"]' -)"
done
if [ -n "$root" ]; then
  export ROOT="$root"
  doc="$(printf '%s\n' "$doc" | yq e '. as $d | {} | .[strenv(ROOT)] = $d' -)"
fi

mkdir -p "$(dirname "$out")"
{
  echo "# Generated by 'make omnia-values' from site.yaml. Do not edit."
  echo "# Each trusted issuer is a stand-in edge (docs/stand-ins.md) that signs the"
  echo "# user's token; a real install replaces them with its own IdP."
  printf '%s\n' "$doc"
} >"$out"

fqdns=()
for h in $(poppy_dns_names); do
  fqdns+=("$h.$zone")
done
fqdns+=("$dashboard")
echo "TLS hosts: ${fqdns[*]}"
